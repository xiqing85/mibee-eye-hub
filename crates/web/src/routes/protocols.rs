// Schema definitions — generated from Rust config structs via `schemars`.
// Numeric / boolean fields sent as strings are coerced (for backward
// compatibility with older frontends). Unknown fields are rejected.
// ---------------------------------------------------------------------------

/// Generate a JSON Schema for the given protocol's config struct.
/// The schema is derived at compile time from the Rust type definitions,
/// eliminating the need for a hand-maintained field table.
fn schema_for(protocol: &str) -> serde_json::Value {
    let schema = match protocol {
        "onvif" => schemars::schema_for!(crate::config::OnvifConfig),
        "gb28181" => schemars::schema_for!(crate::config::Gb28181Config),
        "rtmp_push" => schemars::schema_for!(crate::config::RtmpPushConfig),
        "recording" => schemars::schema_for!(crate::config::RecordingConfig),
        "webrtc" => schemars::schema_for!(crate::config::WebRtcConfig),
        "watermark" => schemars::schema_for!(crate::config::WatermarkConfig),
        _ => return serde_json::json!({}),
    };
    serde_json::to_value(&schema).unwrap_or_else(|_| serde_json::json!({}))
}

fn type_name(v: &serde_json::Value) -> &'static str {
    match v {
        serde_json::Value::Null => "null",
        serde_json::Value::Bool(_) => "bool",
        serde_json::Value::Number(_) => "number",
        serde_json::Value::String(_) => "string",
        serde_json::Value::Array(_) => "array",
        serde_json::Value::Object(_) => "object",
    }
}

/// Coerce a JSON number-or-numeric-string into u64, bounded by [min, max].
fn coerce_uint(v: serde_json::Value, min: u64, max: u64) -> Result<u64, String> {
    match v {
        serde_json::Value::Number(n) => {
            let as_u64 = n
                .as_u64()
                .ok_or_else(|| format!("expected integer, got float {:?}", n))?;
            if as_u64 < min || as_u64 > max {
                return Err(format!(
                    "integer {} out of range [{}, {}]",
                    as_u64, min, max
                ));
            }
            Ok(as_u64)
        }
        // Accept numeric strings from legacy frontends.
        serde_json::Value::String(s) => {
            let parsed: i64 = s
                .parse()
                .map_err(|_| format!("expected integer, got string {:?}", s))?;
            if parsed < 0 {
                return Err(format!(
                    "integer {} out of range [{}, {}]",
                    parsed, min, max
                ));
            }
            let parsed_u64 = parsed as u64;
            if parsed_u64 < min || parsed_u64 > max {
                return Err(format!(
                    "integer {} out of range [{}, {}]",
                    parsed_u64, min, max
                ));
            }
            Ok(parsed_u64)
        }
        other => Err(format!("expected integer, got {}", type_name(&other))),
    }
}

/// Extract a u64 from a JSON Schema constraint value, handling both integer
/// and float representations that schemars may emit (e.g. `65535` vs `65535.0`).
fn schema_u64(v: Option<&serde_json::Value>, default: u64) -> u64 {
    v.and_then(|v| v.as_u64().or_else(|| v.as_f64().map(|f| f as u64)))
        .unwrap_or(default)
}

/// Resolve a `$ref` (e.g. `#/definitions/Gb35114Config`) against the root
/// schema, returning the referenced subschema. Non-ref schemas pass through.
/// schemars 0.8 wraps struct fields in `{"allOf": [{$ref}]}` when they carry
/// a `default` — unwrap that too.
fn resolve_ref<'a>(
    root: &'a serde_json::Value,
    schema: &'a serde_json::Value,
) -> &'a serde_json::Value {
    if let Some(all_of) = schema.get("allOf").and_then(|a| a.as_array())
        && all_of.len() == 1
    {
        return resolve_ref(root, &all_of[0]);
    }
    let ref_path = match schema.get("$ref").and_then(|r| r.as_str()) {
        Some(r) => r,
        None => return schema,
    };
    // Only `#/definitions/Name` refs are generated by schemars 0.8.
    ref_path
        .strip_prefix("#/definitions/")
        .and_then(|name| root.get("definitions").and_then(|d| d.get(name)))
        .unwrap_or(schema)
}

/// Validate + coerce a JSON object against an object schema's `properties`.
/// Rejects unknown keys at every nesting level and coerces leaf values.
fn validate_object(
    root: &serde_json::Value,
    obj_schema: &serde_json::Value,
    obj: &serde_json::Map<String, serde_json::Value>,
) -> Result<serde_json::Value, String> {
    let empty_map = serde_json::Map::new();
    let properties = obj_schema
        .get("properties")
        .and_then(|p| p.as_object())
        .unwrap_or(&empty_map);

    for k in obj.keys() {
        if !properties.contains_key(k) {
            return Err(format!("unknown field {:?}", k));
        }
    }

    let mut out = serde_json::Map::new();
    for (k, v) in obj {
        let prop_schema = resolve_ref(root, properties.get(k).expect("checked above"));
        let coerced = coerce_value(root, prop_schema, v.clone())
            .map_err(|e| format!("field {:?}: {}", k, e))?;
        out.insert(k.clone(), coerced);
    }
    Ok(serde_json::Value::Object(out))
}

/// Coerce a JSON value to match the type declared in the (ref-resolved)
/// property schema. Object values recurse so nested config sections get the
/// same unknown-field rejection and legacy-string coercion as the top level.
fn coerce_value(
    root: &serde_json::Value,
    prop_schema: &serde_json::Value,
    v: serde_json::Value,
) -> Result<serde_json::Value, String> {
    if let serde_json::Value::Object(ref inner) = v {
        let schema = resolve_ref(root, prop_schema);
        if schema.get("properties").is_some() {
            return validate_object(root, schema, inner);
        }
    }
    coerce_leaf(prop_schema, v)
}

/// Coerce a JSON value to match the type declared in the JSON Schema property.
/// Boolean and numeric fields sent as strings are coerced for backward
/// compatibility with legacy frontends.
fn coerce_leaf(
    prop_schema: &serde_json::Value,
    v: serde_json::Value,
) -> Result<serde_json::Value, String> {
    let ty = prop_schema
        .get("type")
        .and_then(|t| t.as_str())
        .unwrap_or("");
    match ty {
        "boolean" => match v {
            serde_json::Value::Bool(_) => Ok(v),
            // Accept string "true" / "false" from legacy frontends.
            serde_json::Value::String(s) => match s.parse::<bool>() {
                Ok(b) => Ok(serde_json::Value::Bool(b)),
                Err(_) => Err(format!("expected bool, got string {:?}", s)),
            },
            other => Err(format!("expected bool, got {}", type_name(&other))),
        },
        "integer" => {
            let min = schema_u64(prop_schema.get("minimum"), 0);
            let max = schema_u64(prop_schema.get("maximum"), u64::MAX);
            coerce_uint(v, min, max).map(serde_json::Value::from)
        }
        "string" => match v {
            serde_json::Value::String(ref s) => {
                // Enum-constrained strings (e.g. watermark.position) must be
                // one of the schema's declared values.
                if let Some(allowed) = prop_schema.get("enum").and_then(|e| e.as_array())
                    && !allowed.iter().any(|a| a.as_str() == Some(s.as_str()))
                {
                    let values = allowed
                        .iter()
                        .filter_map(|a| a.as_str())
                        .collect::<Vec<_>>()
                        .join(", ");
                    return Err(format!("value {s:?} not in [{values}]"));
                }
                // maxLength (char count) when the schema declares one.
                if let Some(max_len) = prop_schema.get("maxLength")
                    && let Some(max_len) = max_len
                        .as_u64()
                        .or_else(|| max_len.as_f64().map(|f| f as u64))
                    && s.chars().count() as u64 > max_len
                {
                    return Err(format!(
                        "string length {} exceeds maxLength {max_len}",
                        s.chars().count()
                    ));
                }
                Ok(v)
            }
            other => Err(format!("expected string, got {}", type_name(&other))),
        },
        _ => Ok(v),
    }
}

/// Validate + coerce a partial update payload against the generated JSON Schema.
/// Returns the coerced object containing only known fields (at every nesting
/// level). Unknown fields trigger an error.
pub(crate) fn validate_and_coerce(
    protocol: &str,
    payload: &serde_json::Value,
) -> Result<serde_json::Value, String> {
    let obj = match payload.as_object() {
        Some(o) => o,
        None => {
            return Err(format!(
                "expected JSON object for {} config update, got {}",
                protocol,
                type_name(payload)
            ));
        }
    };

    let schema = schema_for(protocol);
    match validate_object(&schema, &schema, obj) {
        Ok(v) => Ok(v),
        Err(e) if e.starts_with("unknown field") => Err(format!(
            "{} for {} config; if this is a new setting, add it to the struct in config.rs first",
            e, protocol
        )),
        Err(e) => Err(e),
    }
}
